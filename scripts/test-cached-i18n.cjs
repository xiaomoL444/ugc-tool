/* Ordinary Vue I18n labels follow locale and loaded dictionary changes. */
const assert = require('node:assert/strict');
const { computed } = require('vue');
global.window = {};
const { createAppI18n } = require('./i18n-test-helpers.cjs').publicI18n();
const composer = createAppI18n('zh-CN').global;
composer.setLocaleMessage('zh-CN', { resourceProbe: { name: '烟尘' } });
composer.setLocaleMessage('en-US', { resourceProbe: { name: 'Smoke' } });
const t = composer.t;
const label = computed(() => t('resourceProbe.name'));
assert.equal(label.value, '烟尘');
assert.equal(t('resourceProbe.missing'), 'resourceProbe.missing', 'Missing resources return their full key');
composer.setLocaleMessage('zh-CN', { resourceProbe: { name: '新烟尘', missing: '已加载' } });
assert.equal(label.value, '新烟尘', 'An arriving dictionary updates the existing computed label');
assert.equal(t('resourceProbe.missing'), '已加载', 'Newly loaded keys become visible');
composer.locale.value = 'en-US';
assert.equal(label.value, 'Smoke');
assert.equal(t('resourceProbe.missing'), 'resourceProbe.missing', 'No cross-language fallback');
composer.setLocaleMessage('zh-CN', { resourceProbe: { name: '再次更新' } });
assert.equal(label.value, 'Smoke', 'Background-language updates leave the active label unchanged');
composer.locale.value = 'zh-CN';
assert.equal(label.value, '再次更新');
composer.setLocaleMessage('zh-CN', {});
assert.equal(label.value, 'resourceProbe.name', 'Removed entries display the full key');
console.log('PASS ordinary t: locale switching, dictionary updates and missing resource keys');
